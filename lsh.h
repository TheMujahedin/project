
// Δηλώσεις κλάσης και δομών για τον αλγόριθμο Locality Sensitive Hashing (LSH) σε Ευκλείδειο χώρο (L2).
//
//Ο αλγόριθμος LSH χρησιμοποιεί τυχαίες προβολές p-stable (Gaussian) κατανομών για να διαμερίσει 
//τον συνεχή χώρο των διανυσμάτων BoVW σε κάδους κατακερματισμού (buckets). Σημεία με μικρή 
//Ευκλείδεια απόσταση έχουν υψηλή πιθανότητα σύγκρουσης (collision) στον ίδιο κάδο.
//
//Χαρακτηριστικά λειτουργίας:
//- Χρήση L_tables ανεξάρτητων πινάκων κατακερματισμού για αύξηση της ανάκλησης (Recall).
//- Κάθε πίνακας συνδυάζει k_hash στοιχειώδεις συναρτήσεις h_i(x) σε μία σύνθετη συνάρτηση g(x).
//- Ενίσχυση της διακριτότητας μέσω τυχαίων βαρών r_weights για την παραγωγή του hash key.
//- Προσεγγιστική ανάκτηση εξετάζοντας αποκλειστικά τα σημεία που συγκρούονται στους κάδους του ερωτήματος.
//

#ifndef LSH_H
#define LSH_H

#include "features.h"
#include <vector>
#include <unordered_map>
#include <string>


// Αναπαράσταση μιας στοιχειώδους Ευκλείδειας συνάρτησης κατακερματισμού LSH.
//
//Ορίζεται ως h(x) = floor((x * v + t) / w).
//
struct LSHFunction {
    std::vector<float> v; ///< Τυχαίο διάνυσμα προβολής διαστάσεων dim, v ~ N(0, 1).
    float t;              ///< Τυχαία ομοιόμορφη μετατόπιση (offset), t ~ U[0, w).
};

class LSHIndex {
private:
    int k_hash;                 // Αριθμός στοιχειωδών συναρτήσεων h_i ανά πίνακα κατακερματισμού.
    int L_tables;               // Αριθμός ανεξάρτητων πινάκων κατακερματισμού (hash tables).
    double w_width;             // Μέγεθος παραθύρου προβολής (slot window width w).
    int dim;                    // Διάσταση των διανυσμάτων BoVW (d = 256).
    unsigned int table_size;    // Μέγεθος του hash table (modulo) για τον περιορισμό του εύρους κλειδιών.

    /// L πίνακες συναρτήσεων: κάθε πίνακας περιλαμβάνει k_hash συναρτήσεις LSHFunction.
    std::vector<std::vector<LSHFunction>> hash_functions;

    /// Τυχαίοι ακέραιοι συντελεστές r_i για τη γραμμική σύνθεση g(x) = sum(r_i * h_i) mod TableSize.
    std::vector<std::vector<int>> r_weights;

    /// L πίνακες κατακερματισμού: bucket_key -> λίστα δεικτών (indices) των διανυσμάτων στη database.
    std::vector<std::unordered_map<int, std::vector<int>>> tables;

    /// Αναφορά στη βάση δεδομένων των εικόνων (HPatches βάση + MIRFlickr distractors).
    const std::vector<ImageRecord>& database;

    //
    // Υπολογισμός της στοιχειώδους συνάρτησης h(x) = floor((x * v + t) / w).
    //
    // x Δείκτης στον πίνακα των συντεταγμένων του διανύσματος (float[256]).
    // fn Η συνάρτηση κατακερματισμού (διάνυσμα v και μετατόπιση t).
    //return int Η ακέραια τιμή του κάδου προβολής.
    //
    int compute_h(const float* x, const LSHFunction& fn) const;

    //
     // Υπολογισμός της σύνθετης συνάρτησης κατακερματισμού g(x) για έναν συγκεκριμένο πίνακα.
     //
     //Συνδυάζει τις k_hash τιμές h_i με τα βάρη r_i: g(x) = (sum_{j=1}^k r_j * h_j(x)) mod TableSize.
     //
     // x Δείκτης στον πίνακα συντεταγμένων του διανύσματος.
     // table_idx Ο δείκτης του πίνακα κατακερματισμού (0 έως L_tables - 1).
     //return int Το τελικό κλειδί κάδου (bucket key) του πίνακα.
     //
    int compute_g(const float* x, int table_idx) const;

public:
    //
    // Κατασκευαστής του ευρετηρίου LSH.
    //
    // db Αναφορά στη βάση δεδομένων εικόνων.
    // k Αριθμός συναρτήσεων h_i ανά πίνακα (π.χ. k = 4).
    // L Αριθμός πινάκων κατακερματισμού (π.χ. L = 5).
    // w Μέγεθος παραθύρου προβολής (π.χ. w = 1.0).
    // dimension Διάσταση των διανυσμάτων εισόδου (256).
    // seed Σπόρος γεννήτριας τυχαίων αριθμών για επαναληψιμότητα.
    //
    LSHIndex(const std::vector<ImageRecord>& db, int k, int L, double w, int dimension, unsigned int seed);

    //
    // Κατασκευή του ευρετηρίου (εισαγωγή όλων των διανυσμάτων της βάσης στους L πίνακες).
    //
    void build();

    //
    // Εκτέλεση προσεγγιστικής αναζήτησης για την εύρεση των top-k πλησιέστερων εικόνων.
    //
    //Εντοπίζει τους υποψηφίους από τους αντίστοιχους κάδους των L πινάκων, απομακρύνει
    //τα διπλότυπα και υπολογίζει την πραγματική Ευκλείδεια απόσταση L2 μόνο για αυτούς.
    //
    // query_vec Το κανονικοποιημένο BoVW διάνυσμα του ερωτήματος (query).
    // top_k Ο αριθμός των πλησιέστερων γειτόνων προς ανάκτηση (προεπιλογή: 10).
    //return std::vector<std::string> Λίστα με τα αναγνωριστικά (IDs) των top-k εικόνων σε αύξουσα σειρά απόστασης.
    //
    std::vector<std::string> search(const std::vector<float>& query_vec, int top_k = 10) const;
};

#endif // LSH_H